// node tools/gen-books-data.js [books_dir]  — regenerates docs/books-data.js for the 📚 Books کتابیں picker
// from the canonical tables in /workspace/geronimo-map/books/<work>.json (one file per work).
// Geronimo is NOT included here: it stays in docs/geronimo-books.js and keeps its own logic in approve.js.
const fs = require("fs"), path = require("path");
const dir = process.argv[2] || "/workspace/geronimo-map/books";
const META = {
  lotr:        { icon: "💍", en: "The Lord of the Rings", ur: "دی لارڈ آف دی رنگز", unitName: "chapter" },
  shakespeare: { icon: "🎭", en: "Shakespeare's plays", ur: "شیکسپیئر کے ڈرامے", unitName: "play" },
  sonnets:     { icon: "📜", en: "Shakespeare's Sonnets", ur: "شیکسپیئر کی سانیٹ", unitName: "sonnet" },
  kashf:       { icon: "🕯️", en: "Kashf al-Mahjub", ur: "کشف المحجوب", unitName: "chapter" },
  artofwar:    { icon: "🏯", en: "The Art of War", ur: "فنِ جنگ", unitName: "chapter" },
  fusus:       { icon: "💎", en: "Fusus al-Hikam", ur: "فصوص الحکم", unitName: "fass" },
};
const works = Object.keys(META).map((id) => {
  const W = JSON.parse(fs.readFileSync(path.join(dir, id + ".json"), "utf8"));
  if (W.entries.length !== W.N) throw new Error(id + ": entries != N");
  const su = W.sub_unit;
  const units = W.entries.map((e) => {
    const u = { n: e.number, title: e.title, ar: e.title_ar, ja: e.title_ja, summary: e.summary };
    if (id === "lotr") u.label = `Book ${e.book} · ch ${e.chapter_in_book}`;
    if (id === "artofwar") u.label = `${e.roman}`;
    if (id === "kashf") u.label = `ch ${e.number}`;
    if (id === "fusus") { u.label = `fass ${e.number} · ${e.prophet}`; u.en = e.title_en; }
    if (id === "shakespeare") u.spa = e.scenes_per_act;
    if (su) u.subs = e[su.count_field];
    if (W.rights !== "copyrighted") {           // public-domain lines only; LOTR never gets one
      if (e.pd_lines) u.lines = e.pd_lines; else if (e.pd_line) u.line = e.pd_line;
    }
    return u;
  });
  return Object.assign({ id, N: W.N, ar: W.title_ar, ja: W.title_ja, rights: W.rights, subName: su ? su.name : null,
    lineSource: id === "artofwar" ? "Giles 1910 (public domain)" : id === "sonnets" ? "opening line, PG #1041" : id === "shakespeare" ? "PG #100 (public domain)" : null,
    source: W.structure_source_url, units }, META[id]);
});
const out = `/* 📚 Books کتابیں — GENERATED by tools/gen-books-data.js from /workspace/geronimo-map/books/*.json. Do not edit by hand.
   Number pairing only: unit = ((S-1) mod N)+1; sub-unit = ((A-1) mod subs)+1 where a work has one.
   The Lord of the Rings is copyrighted: titles, numbers and our own summaries only, never a line of text.
   Other lines are public domain (Shakespeare PG #100/#1041, Giles 1910). */
(function (root) {
  const BOOK_WORKS = ${JSON.stringify({ works })};
  if (typeof module !== "undefined") module.exports = BOOK_WORKS; else root.BOOK_WORKS = BOOK_WORKS;
})(typeof window !== "undefined" ? window : globalThis);
`;
fs.writeFileSync(path.join(__dirname, "..", "docs", "books-data.js"), out);
console.log("wrote docs/books-data.js", works.map((w) => `${w.id}=${w.N}`).join(" "), (out.length / 1024).toFixed(1) + " KB");
